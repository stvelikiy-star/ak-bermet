export const roomDetailSlugs = roomDetails.map((r) => r.slug);

export function getRoomDetail(slug: string): RoomDetail | undefined {
  return roomDetails.find((r) => r.slug === slug);
}

// Краткие карточки для обзора /rooms (с привязкой к detail-страницам).
export type RoomOverviewCard = {
  slug: string;
  title: string;
  badge?: string;
  short: string;
  building: string;
  capacity: string;
  wifi: boolean;
  meals: boolean;
  bestForShort: string;
  img: string;
  alt: string;
};

export const roomOverviewCards: RoomOverviewCard[] = roomDetails.map((r) => {
  const wifiFact = r.facts.find((f) => f.label === "Wi-Fi");
  const capFact = r.facts.find((f) => f.label === "Вместимость");
  return {
    slug: r.slug,
    title: r.title,
    badge: r.badge,
    short: r.intro,
    building: r.building,
    capacity: capFact?.value ?? "",
    wifi: (wifiFact?.value ?? "").toLowerCase().startsWith("есть"),
    meals: true,
    bestForShort: r.bestFor[0] ?? "",
    img: r.gallery[0]?.src ?? "",
    alt: r.gallery[0]?.alt ?? r.title,
  };
});
